type LanguageContextValue = { language: AppLanguage; setLanguage: (language: AppLanguage) => void; t: (arabicText: string) => string };
const LanguageContext = createContext<LanguageContextValue | null>(null);
export function LanguageProvider({ children }: { children: ReactNode }) {
  const auth = trpc.auth.me.useQuery();
  const [pathname] = useLocation();
  const saveLanguage = trpc.auth.setLanguage.useMutation();
  const [language, setLanguageState] = useState<AppLanguage>(() => {
    if (typeof window === "undefined") return "ar";
    const saved = window.localStorage.getItem("clientora-language");
    return saved === "en" || saved === "ru" || saved === "fr" || saved === "it" ? saved : "ar";
  });
  useEffect(() => { void auth.refetch(); }, [pathname]);
  useEffect(() => {
    const saved = auth.data?.language;
    if (saved === "ar" || saved === "en" || saved === "ru" || saved === "fr" || saved === "it") setLanguageState(saved);
  }, [auth.data?.language]);
  const setLanguage = useCallback((next: AppLanguage) => {
    setLanguageState(next);
    if (auth.data?.id) saveLanguage.mutate({ language: next });
  }, [auth.data?.id, saveLanguage]);
  useEffect(() => {
    window.localStorage.setItem("clientora-language", language);
    document.documentElement.lang = language;
    document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
  }, [language]);
  const t = (arabicText: string) => language === "ar" ? arabicText : dashboardTranslations[language]?.[arabicText] ?? setupCompanyTranslations[language]?.[arabicText] ?? dictionaries[language]?.[arabicText] ?? dictionaries.en?.[arabicText] ?? arabicText;
  return <LanguageContext.Provider value={{ language, setLanguage, t }}>{children}</LanguageContext.Provider>;
}
export function useLanguage() {
  const value = useContext(LanguageContext);
  if (!value) throw new Error("useLanguage must be used within LanguageProvider");
  return value;
}
